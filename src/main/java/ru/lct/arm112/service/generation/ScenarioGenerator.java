package ru.lct.arm112.service.generation;

import ru.lct.arm112.api.ApiModels.ScenarioUpsert;

import java.util.List;

/**
 * Источник сценариев-кандидатов.
 *
 * <p>Вынесено интерфейсом, чтобы подключение языковой модели было заменой одной реализации,
 * а не переделкой пути. Всё остальное — постановка задачи, очередь, проверка
 * {@link ScenarioValidator}, сохранение, подтверждение преподавателем — от источника
 * не зависит и работает уже сейчас.
 *
 * <p>Кандидат — именно кандидат: генератор ничего не сохраняет и не обязан выдавать
 * годное. Отсев делает валидатор, и только прошедшее попадает в библиотеку.
 */
public interface ScenarioGenerator {

    /** Как называется источник — попадает в отчёт о задаче, чтобы различать прогоны. */
    String name();

    /**
     * Выдать кандидатов.
     *
     * @param count сколько запрошено; вернуть можно меньше, если исходного материала мало
     */
    List<ScenarioUpsert> generate(String category, int count, int difficulty);
}
