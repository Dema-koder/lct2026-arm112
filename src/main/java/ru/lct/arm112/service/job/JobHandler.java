package ru.lct.arm112.service.job;

/**
 * Обработчик фоновой задачи одного вида.
 *
 * <p><b>Обязан быть идемпотентным.</b> Очередь даёт гарантию «хотя бы один раз»:
 * исполнитель может упасть после того, как сделал работу, но до того, как отметил
 * задачу завершённой, и тогда задача будет выдана повторно.
 */
public interface JobHandler {

    /** Вид задачи, который обработчик берёт; совпадает со значением колонки {@code type}. */
    String type();

    /**
     * Выполнить задачу.
     *
     * @param payload то, что положили при постановке
     * @return результат для колонки {@code result}; null — если сохранять нечего
     * @throws Exception любое исключение помечает попытку неудачной и назначает повтор
     */
    String handle(String payload) throws Exception;
}
