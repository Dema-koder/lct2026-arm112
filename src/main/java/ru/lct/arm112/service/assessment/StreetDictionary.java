package ru.lct.arm112.service.assessment;

/**
 * Справочник существующих улиц — то, чего не хватает правилу сверки адреса.
 *
 * <p>Без него нельзя отличить два принципиально разных случая:
 * <ul>
 *   <li><b>опечатка</b> — набрано несуществующее название, похожее на эталон;</li>
 *   <li><b>другая улица</b> — набрано название реально существующей улицы, но не той.
 *       Расчёт уедет в другой район, и это тяжелее опечатки.</li>
 * </ul>
 *
 * <p>Расстояние Левенштейна их не различает: «Белозерская» и «Беломорская» отличаются
 * на два символа, как и настоящая опечатка, но обе улицы существуют в Москве.
 */
@FunctionalInterface
public interface StreetDictionary {

    /** Справочника нет — сверка работает по старому правилу, только на расстоянии. */
    StreetDictionary EMPTY = name -> false;

    /**
     * Существует ли улица с таким названием.
     *
     * @param normalizedName название, уже приведённое {@link TextUtil#normalize} —
     *                       без типа улицы, в нижнем регистре, «ё» заменена на «е»
     */
    boolean exists(String normalizedName);
}
